    static int pluginIdFor(int discordId) {
        int low = 0;
        int high = DISCORD_IDS.length - 1;
        while (low <= high) {
            int mid = (low + high) >>> 1;
            int value = DISCORD_IDS[mid];
            if (value < discordId) low = mid + 1;
            else if (value > discordId) high = mid - 1;
            else return PLUGIN_IDS[mid];
        }
        return 0;
    }

